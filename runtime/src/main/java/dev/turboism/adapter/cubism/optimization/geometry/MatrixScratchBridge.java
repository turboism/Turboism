    private static ClassWriter frameWriter(final ClassLoader hostLoader) {
        return new ClassWriter(ClassWriter.COMPUTE_FRAMES | ClassWriter.COMPUTE_MAXS) {
            @Override
            protected ClassLoader getClassLoader() {
                return hostLoader == null ? super.getClassLoader() : hostLoader;
            }

            @Override
            protected String getCommonSuperClass(final String left, final String right) {
                try {
                    return super.getCommonSuperClass(left, right);
                } catch (final Throwable failure) {
                    FatalErrors.rethrowIfFatal(failure);
                    return OBJECT_INTERNAL;
                }
            }
        };
    }

    private static final class AccessorLoader extends ClassLoader implements Supplier<Object> {
        private final Map<String, byte[]> classes;
        private Object bootstrapPayload;

        AccessorLoader(
                final ClassLoader parent,
                final Map<String, byte[]> classes,
                final MethodHandle bootstrapPayload) {
            super(parent);
            this.classes = classes;
            this.bootstrapPayload = bootstrapPayload;
        }

        @Override
        public Object get() {
            final Object payload = bootstrapPayload;
            bootstrapPayload = null;
            return payload;
        }

        @Override
        protected Class<?> loadClass(final String name, final boolean resolve) throws ClassNotFoundException {
            final byte[] bytecode = classes.get(name);
            if (bytecode != null) {
                Class<?> loaded = findLoadedClass(name);
                if (loaded == null) {
                    loaded = defineClass(name, bytecode, 0, bytecode.length);
                }
                if (resolve) {
                    resolveClass(loaded);
                }
                return loaded;
            }
            return super.loadClass(name, resolve);
        }
    }

