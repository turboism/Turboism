def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def client_policy(enabled: bool = True, endpoint: str = ENDPOINT) -> dict:
    return {"schemaVersion": 1, "enabled": enabled, "endpoint": endpoint}


def agent_jar(
    public: bytes, policy: dict | None = None, keyring: dict | None = None
) -> bytes:
    data = io.BytesIO()
    fields = {
        "Manifest-Version": "1.0",
        "Implementation-Version": IDENTITY["version"],
        "Turboism-Version": IDENTITY["version"],
        "Turboism-Channel": IDENTITY["channel"],
        "Turboism-Build-Number": str(IDENTITY["buildNumber"]),
        "Turboism-Source-Revision": IDENTITY["sourceRevision"],
    }
    properties = {**IDENTITY, "buildKind": "ci", "dirty": "false"}
    with zipfile.ZipFile(data, "w") as jar:
        jar.writestr(
            "META-INF/MANIFEST.MF",
            "\r\n".join(f"{key}: {value}" for key, value in fields.items())
            + "\r\n\r\n",
        )
        jar.writestr(
            "META-INF/turboism/framework-version.properties",
            "\n".join(f"{key}={value}" for key, value in properties.items()) + "\n",
        )
        if policy is not None:
            jar.writestr(
                "META-INF/turboism/" + CLIENT_RESOURCE, canonical_bytes(policy) + b"\n"
            )
        if keyring is not None:
            jar.writestr(
                "META-INF/turboism/" + KEYS_RESOURCE, canonical_bytes(keyring) + b"\n"
            )
    return data.getvalue()


def plugin_jar(module: str) -> bytes:
    """A minimal installer-compatible plugin JAR (descriptor plus the four localizations)."""
    data = io.BytesIO()
    with zipfile.ZipFile(data, "w") as jar:
        jar.writestr(
            "META-INF/turboism/plugin.json",
            json.dumps(
                {
                    "id": "turboism." + module,
                    "name": "Fixture " + module,
                    "version": "1.0.0",
                    "description": "fixture plugin " + module,
                    "category": "fixture",
                    "tags": ["fixture"],
                }
            ),
        )
        for suffix in ("en", "zh_Hans", "ja", "ko"):
            jar.writestr(
                f"META-INF/turboism/i18n/messages_{suffix}.properties",
                "plugin.name=Fixture "
                + module
                + "\nplugin.description=fixture plugin\n",
            )
    return data.getvalue()


class Workspace:
    """A throwaway repository tree whose release shell paths are real."""

    def __init__(self, root: Path, agent: bytes):
        self.root = root
        self.staging = root / "build/windows-installer/staging"
        self.dist = root / "build/windows-installer/dist"
        self.generated = root / "build/windows-installer/generated"
        self.developer = root / "build/worktree/test-worktree/event-processor/libs"
        self.documents = root / "build/release-orchestrator/framework-update"
        self.bundle = root / "build/release-orchestrator"
        for directory in (self.staging, self.dist, self.developer, self.bundle):
            directory.mkdir(parents=True, exist_ok=True)
        shutil.copytree(
            ROOT / "packaging/windows-installer",
            root / "packaging/windows-installer",
            dirs_exist_ok=True,
            ignore=shutil.ignore_patterns("*.nsh", "*.log"),
        )
        shutil.copy2(
            ROOT / "packaging/release-plugins.txt",
            root / "packaging/release-plugins.txt",
        )
        (root / "scripts/dev").mkdir(parents=True, exist_ok=True)
        for name in ("worktree-id.sh", "worktree-id-lib.sh"):
            shutil.copy2(ROOT / "scripts/dev" / name, root / "scripts/dev" / name)
        (root / "packaging/eula").mkdir(parents=True, exist_ok=True)
        for language in ("en", "zh-Hans", "ja", "ko"):
            (root / "packaging/eula" / f"EULA.{language}.txt").write_text(
                "eula\n", encoding="utf-8"
            )
        (root / "LICENSE").write_text("license\n", encoding="utf-8")
        (root / "gradle").mkdir()
        gradlew = root / "gradlew"
        gradlew.write_bytes(b"#!/usr/bin/env bash\nexit 0\n")
        gradlew.chmod(0o755)
        (root / "gradle/common-java.gradle.kts").write_text(
            'rootProject.extra["turboismFrameworkVersion"] = "%s"\n' % VERSION,
            encoding="utf-8",
        )
        self.agent = agent

    def populate_payload(self) -> None:
        payload = {
            name: b"payload:" + name.encode("ascii") + b"\n"
            for name in POLICY["frameworkRootFiles"]
            if name != "script-engine.json"
        }
        payload["turboism-agent.jar"] = self.agent
        for name in (
            "sdk-%s.jar" % VERSION,
            "graal-host-%s-test-worktree.jar" % VERSION,
        ):
            payload["graal/lib/" + name] = b"lib:" + name.encode("ascii") + b"\n"
        # The optional script engine is a pinned manifest: both artifacts must exist in staging and
        # agree with gradle/verification-metadata.xml, exactly as the release shell enforces.
        engine = {
            "format": "turboism.optional-script-engine",
            "schemaVersion": 1,
            "version": ENGINE_VERSION,
            "artifacts": [],
        }
        for name in (
            "js-isolate-windows-amd64-community-%s.jar" % ENGINE_VERSION,
            "truffle-api-%s.jar" % ENGINE_VERSION,
        ):
            data = b"engine:" + name.encode("ascii") + b"\n"
            payload["graal/lib/" + name] = data
            engine["artifacts"].append(
                {
                    "name": name,
                    "bytes": len(data),
                    "sha256": hashlib.sha256(data).hexdigest(),
                }
            )
        payload["script-engine.json"] = canonical_bytes(engine) + b"\n"
        pins = "".join(
            '    <artifact name="%s">\n      <sha256 value="%s"/>\n    </artifact>\n'
            % (item["name"], item["sha256"])
            for item in engine["artifacts"]
        )
        (self.root / "gradle/verification-metadata.xml").write_text(
            '<verification-metadata>\n  <components>\n    <component group="fixture" name="engine">\n'
            + pins
            + "    </component>\n  </components>\n</verification-metadata>\n",
            encoding="utf-8",
        )
        plugins = {"plugins/%s.jar" % module: plugin_jar(module) for module in ROSTER}
        for name, data in {**payload, **plugins}.items():
            target = self.staging / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
        (self.staging / "config.template.json").write_text(
            '{"template":true}\n', encoding="utf-8"
        )
        self.payload = payload
        self.plugins = plugins

    def inventory(self) -> Path:
        entries = [
            {
                "relativePath": name,
                "bytes": len(data),
                "sha256": hashlib.sha256(data).hexdigest(),
            }
            for name, data in sorted(self.payload.items())
        ]
        path = self.generated / "framework-payload-inventory.json"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(
            canonical_bytes(
                {
                    "format": "turboism.framework-payload-inventory",
                    "schemaVersion": 1,
                    "layout": POLICY["layout"],
                    "identity": IDENTITY,
                    "files": entries,
                    "excludedPaths": sorted(
                        [*POLICY["excludedStateFiles"], *self.plugins]
                    ),
                }
            )
            + b"\n"
        )
        return path

    def receipt(self) -> Path:
        path = self.bundle / "build-identity.json"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(
            canonical_bytes(
                {
                    "schemaVersion": 1,
                    **IDENTITY,
                    "runId": RUN_ID,
                    "runAttempt": RUN_ATTEMPT,
                }
            )
            + b"\n"
        )
        return path

    def candidate(self) -> Path:
        archive = self.dist / f"turboism-{VERSION}.zip"
        path = self.bundle / "candidate.json"
        path.write_bytes(
            canonical_bytes(
                {
                    "format": "turboism.release-candidate",
                    "schemaVersion": 1,
                    "source": {
                        "repository": "turboism/Turboism",
                        "revision": IDENTITY["sourceRevision"],
                        "tag": None,
                    },
                    "framework": {
                        "eligible": True,
                        "version": VERSION,
                        "artifacts": [
                            {
                                "name": archive.name,
                                "size": archive.stat().st_size,
                                "sha256": sha256(archive),
                            }
                        ],
                    },
                }
            )
            + b"\n"
        )
        return path

    def prerelease_candidate(self) -> Path:
        archive = self.dist / f"turboism-{VERSION}.zip"
        path = self.bundle / "prerelease-candidate.json"
        path.write_bytes(
            canonical_bytes(
                {
                    "schemaVersion": 2,
                    "type": "turboism.prerelease-candidate",
                    "receipt": {
                        "schemaVersion": 1,
                        **IDENTITY,
                        "runId": RUN_ID,
                        "runAttempt": RUN_ATTEMPT,
                    },
                    "manifest": {
                        "format": "turboism.framework-artifacts",
                        "schemaVersion": 1,
                        "version": VERSION,
                        "artifacts": [
                            {
                                "name": archive.name,
                                "mediaType": "application/zip",
                                "size": archive.stat().st_size,
                                "sha256": sha256(archive),
                            }
                        ],
                    },
                    "notesSha256": "0" * 64,
                }
            )
            + b"\n"
        )
        return path

    def assemble(self, *extra: str) -> subprocess.CompletedProcess:
        command = [
            "bash",
            "packaging/windows-installer/assemble-release.sh",
            VERSION,
            "--skip-gradle",
            "--skip-nsis",
            *extra,
        ]
        return subprocess.run(
            command,
            cwd=self.root,
            encoding="utf-8",
            errors="replace",
            capture_output=True,
            env={**os.environ, "TURBOISM_WORKTREE_ID": "test-worktree"},
        )

    def assemble_normal(self) -> subprocess.CompletedProcess:
        """The ordinary build path: Gradle (stubbed to succeed) then the real packaging checks."""
        command = [
            "bash",
            "packaging/windows-installer/assemble-release.sh",
            VERSION,
            "--skip-nsis",
        ]
        return subprocess.run(
            command,
            cwd=self.root,
            encoding="utf-8",
            errors="replace",
            capture_output=True,
            env={**os.environ, "TURBOISM_WORKTREE_ID": "test-worktree"},
        )

    def publish_developer_assets(self) -> None:
        build_output = self.developer / f"event-processor-{VERSION}.jar"
        build_output.parent.mkdir(parents=True, exist_ok=True)
        build_output.write_bytes(b"event-processor:" + VERSION.encode("ascii") + b"\n")
        (self.dist / f"turboism-event-processor-{VERSION}.jar").write_bytes(
            build_output.read_bytes()
        )


class FrameworkReleaseFixture(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="framework-release-test-")
        self.addCleanup(self.temporary.cleanup)
        self.home = Path(self.temporary.name)
        self.key = self.home / "temporary.pem"
        framework_update.openssl(
            ["genpkey", "-algorithm", "Ed25519", "-out", str(self.key)]
        )
        self.key.chmod(0o600)
        self.public = framework_update.openssl(
            ["pkey", "-in", str(self.key), "-pubout", "-outform", "DER"]
        )
        self.keyring = {
            "schemaVersion": 1,
            "keys": {"framework-test": base64.b64encode(self.public).decode("ascii")},
            "revoked": [],
        }
        self.key_variable = "FRAMEWORK_RELEASE_TEST_KEY"
        self.addCleanup(os.environ.pop, self.key_variable, None)
        os.environ[self.key_variable] = self.key.read_text(encoding="ascii")
        self.workspace = Workspace(
            self.home / "repo", agent_jar(self.public, client_policy(), self.keyring)
        )
        self.workspace.populate_payload()
        self.inventory = self.workspace.inventory()
        self.receipt = self.workspace.receipt()

    def first_pass(self) -> Path:
        self.workspace.publish_developer_assets()
        result = self.workspace.assemble()
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        return self.workspace.dist / f"turboism-{VERSION}.zip"

    def sign(self, **changes):
        arguments = dict(
            dist=self.workspace.dist,
            identity_path=self.receipt,
            inventory=self.inventory,
            evidence=self.workspace.candidate(),
            prerelease_evidence=None,
            key_id="framework-test",
            private_key_env=self.key_variable,
            minimum_updater="0.68.0",
            output=self.workspace.documents,
        )
        arguments.update(changes)
        return framework_release.sign(**arguments)

    def final_package(self) -> Path:
        self.first_pass()
        self.sign()
        result = self.workspace.assemble(
            "--bootstrap-receipt-dir", "build/release-orchestrator/framework-update"
        )
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        return self.workspace.dist / f"turboism-{VERSION}.zip"

    def verify(self, **changes):
        arguments = dict(
            dist=self.workspace.dist,
            documents=self.workspace.documents,
            inventory=self.inventory,
            identity_path=self.receipt,
            evidence_output=self.workspace.bundle / "framework-bootstrap-evidence.json",
        )
        arguments.update(changes)
        return framework_release.verify(**arguments)

    def evidence(self) -> dict:
        return json.loads(
            (self.workspace.bundle / "framework-bootstrap-evidence.json").read_text(
                encoding="utf-8"
            )
        )

    @staticmethod
    def replace_member(archive: Path, member: str, data: bytes) -> None:
        original = archive.read_bytes()
        with (
            zipfile.ZipFile(io.BytesIO(original)) as source,
            zipfile.ZipFile(archive, "w") as target,
        ):
            for info in source.infolist():
                payload = source.read(info.filename)
                target.writestr(info, data if info.filename == member else payload)


class RepackagingShellTest(FrameworkReleaseFixture):
    """The real release shell data paths, including a ``--skip-gradle`` re-packaging pass."""

    def test_skip_gradle_reuses_verified_developer_assets_and_restores_them(self):
        archive = self.first_pass()
        first_dist = {
            path.name: sha256(path)
            for path in self.workspace.dist.iterdir()
            if path.is_file()
        }
        self.assertIn(f"turboism-event-processor-{VERSION}.jar", first_dist)
        self.assertIn(f"turboism-sdk-{VERSION}.jar", first_dist)
        with zipfile.ZipFile(archive) as package:
            self.assertNotIn("bootstrap/manifest.json", package.namelist())
        # A signing job has no Gradle build outputs: only the published dist/stage survive.
        shutil.rmtree(self.workspace.root / "build/worktree")
        self.sign()
        second = self.workspace.assemble(
            "--bootstrap-receipt-dir", "build/release-orchestrator/framework-update"
        )
        self.assertEqual(second.returncode, 0, second.stdout + second.stderr)
        second_dist = {
            path.name: sha256(path)
            for path in self.workspace.dist.iterdir()
            if path.is_file()
        }
        self.assertEqual(
            first_dist[f"turboism-event-processor-{VERSION}.jar"],
            second_dist[f"turboism-event-processor-{VERSION}.jar"],
        )
        self.assertEqual(
            first_dist[f"turboism-sdk-{VERSION}.jar"],
            second_dist[f"turboism-sdk-{VERSION}.jar"],
        )
        self.assertNotEqual(first_dist[archive.name], second_dist[archive.name])
        sidecar = self.workspace.dist / (archive.name + ".sha256")
        self.assertEqual(
            sidecar.read_text(encoding="utf-8").strip(),
            f"{sha256(archive)}  {archive.name}",
        )
        with zipfile.ZipFile(archive) as package:
            names = package.namelist()
        self.assertEqual(
            sorted(name for name in names if name.startswith("bootstrap/")),
            sorted(framework_release.BOOTSTRAP_DOCUMENTS),
        )

    def test_skip_gradle_ignores_a_local_gradle_event_processor(self):
        archive = self.first_pass()
        published = (
            self.workspace.dist / f"turboism-event-processor-{VERSION}.jar"
        ).read_bytes()
        # A different same-version JAR appears in the local Gradle output; skip-gradle must not adopt it.
        (self.workspace.developer / f"event-processor-{VERSION}.jar").write_bytes(
            b"different:" + published
        )
        self.sign()
        result = self.workspace.assemble(
            "--bootstrap-receipt-dir", "build/release-orchestrator/framework-update"
        )
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertEqual(
            (
                self.workspace.dist / f"turboism-event-processor-{VERSION}.jar"
            ).read_bytes(),
            published,
        )
        self.assertTrue(archive.is_file())

    def test_normal_build_never_falls_back_to_an_older_dist_artifact(self):
        self.first_pass()
        published = self.workspace.dist / f"turboism-event-processor-{VERSION}.jar"
        self.assertTrue(published.is_file())
        shutil.rmtree(self.workspace.developer)
        result = self.workspace.assemble_normal()
        self.assertNotEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn("event-processor", result.stderr)

    def test_final_package_is_owned_plus_excluded_plus_documents(self):
        self.final_package()
        evidence = self.verify()
        self.assertEqual(evidence["identity"], IDENTITY)
        self.assertEqual(evidence["payload"]["entries"], len(self.workspace.payload))
        self.assertEqual(
            evidence["payload"]["excluded"],
            len(POLICY["excludedStateFiles"]) + len(ROSTER),
        )
        with zipfile.ZipFile(
            self.workspace.dist / f"turboism-{VERSION}.zip"
        ) as package:
            names = set(package.namelist())
        # The release ZIP really carries the mutable state and plugin exclusions the producer refuses to own.
        self.assertIn("config.json", names)
        self.assertIn("installed-build.json", names)
        self.assertTrue({"plugins/%s.jar" % module for module in ROSTER} <= names)
        self.assertEqual(
            names
            - set(self.workspace.payload)
            - {"config.json", "installed-build.json"}
            - {"plugins/%s.jar" % module for module in ROSTER},
            set(framework_release.BOOTSTRAP_DOCUMENTS),
        )


class VerificationContractTest(FrameworkReleaseFixture):
    def test_verify_accepts_the_real_release_package(self):
        self.final_package()
        evidence = self.verify()
        self.assertEqual(evidence["format"], framework_release.EVIDENCE_FORMAT)
        self.assertEqual(evidence["keyId"], "framework-test")
        self.assertEqual(
            evidence["archive"]["sha256"],
            sha256(self.workspace.dist / f"turboism-{VERSION}.zip"),
        )
        manifest = self.workspace.documents / f"turboism-{VERSION}-manifest.json"
        self.assertNotIn(b"bootstrap/", manifest.read_bytes())
        self.assertNotIn(b"plugins/", manifest.read_bytes())

    def test_minimum_updater_is_an_explicit_baseline_not_the_target_version(self):
        # Release B must stay applicable to an installation still running the older A, so the floor is
        # the provided compatible baseline and never the version being released.
        self.final_package()
        manifest = json.loads(
            (self.workspace.documents / f"turboism-{VERSION}-manifest.json").read_text(
                encoding="utf-8"
            )
        )
        self.assertEqual(manifest["minimumUpdaterVersion"], "0.68.0")
        self.assertNotEqual(manifest["minimumUpdaterVersion"], VERSION)

    def test_verify_rejects_payload_drift_and_unknown_entries(self):
        archive = self.final_package()
        self.verify()
        original = archive.read_bytes()
        with zipfile.ZipFile(io.BytesIO(original)) as source:
            with zipfile.ZipFile(archive, "w") as package:
                for info in source.infolist():
                    data = source.read(info.filename)
                    package.writestr(
                        info,
                        data + b"tampered" if info.filename == "README.txt" else data,
                    )
        with self.assertRaises(ReleaseError):
            self.verify()
        archive.write_bytes(original)
        self.verify()
        with zipfile.ZipFile(archive, "a") as package:
            package.writestr("bootstrap/extra.json", b"{}")
        with self.assertRaises(ReleaseError):
            self.verify()
        archive.write_bytes(original)
        with zipfile.ZipFile(archive, "a") as package:
            package.writestr("plugins/unknown.jar", b"unexpected")
        with self.assertRaises(ReleaseError):
            self.verify()

    def test_verify_rejects_receipt_and_inventory_mismatch(self):
        self.final_package()
        other = self.workspace.bundle / "other-identity.json"
        other.write_bytes(
            canonical_bytes(
                {
                    "schemaVersion": 1,
                    **{**IDENTITY, "buildNumber": 78},
                    "runId": RUN_ID,
                    "runAttempt": RUN_ATTEMPT,
                }
            )
            + b"\n"
        )
        with self.assertRaises(ReleaseError):
            self.verify(identity_path=other)
        inventory = json.loads(self.inventory.read_text(encoding="utf-8"))
        inventory["excludedPaths"] = sorted(
            [*POLICY["excludedStateFiles"], "plugins/unknown-plugin.jar"]
        )
        self.inventory.write_bytes(canonical_bytes(inventory) + b"\n")
        with self.assertRaises(ReleaseError):
            self.verify()

    def test_beta_candidate_adapts_the_real_identity(self):
        self.first_pass()
        stock = self.sign(
            evidence=None, prerelease_evidence=self.workspace.prerelease_candidate()
        )
        self.assertEqual(stock["identity"], IDENTITY)

    def test_nightly_is_refused_by_the_signing_channels(self):
        self.first_pass()
        receipt = self.workspace.bundle / "nightly-identity.json"
        receipt.write_bytes(
            canonical_bytes(
                {
                    "schemaVersion": 1,
                    **{**IDENTITY, "channel": "nightly"},
                    "runId": RUN_ID,
                    "runAttempt": RUN_ATTEMPT,
                }
            )
            + b"\n"
        )
        with self.assertRaises(ReleaseError):
            self.sign(identity_path=receipt)

    def test_no_key_material_is_written_anywhere(self):
        self.final_package()
        # The fixture key itself lives outside the release workspace on purpose.
        for path in (self.home / "repo").rglob("*"):
            if path.is_file():
                self.assertNotIn(b"PRIVATE KEY", path.read_bytes(), path)


class ShippedActivationTest(FrameworkReleaseFixture):
    """The release refuses to sign or publish a package whose shipped activation is not usable."""

    def shipped_agent_variant(self, policy: dict | None, keyring: dict | None) -> Path:
        archive = self.first_pass()
        self.replace_member(
            archive, "turboism-agent.jar", agent_jar(self.public, policy, keyring)
        )
        return archive

    def test_missing_client_resources_are_refused_before_any_key_is_read(self):
        archive = self.shipped_agent_variant(None, None)
        os.environ.pop(self.key_variable, None)
        with self.assertRaisesRegex(ReleaseError, "framework update client resources"):
            framework_release.shipped_activation(archive)
